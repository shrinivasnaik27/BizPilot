"""Marketing Agent: Generates personalized email drafts for qualified prospects."""
import json, asyncio
from typing import List, Optional
from pydantic import BaseModel, Field
from datetime import datetime, timezone
from ..services.llm_service import llm_service
from ..agents.research_agent import ProspectResearch
from ..agents.analysis_agent import LeadScore
from ..utils.logger import get_logger

logger = get_logger(__name__)

class EmailDraft(BaseModel):
    company_name: str
    subject: str
    body: str
    marketing_angle: str
    personalization_notes: str
    recipient_email: str = Field(default="unknown")
    is_demo: bool = False

class MarketingResult(BaseModel):
    drafts: List[EmailDraft]
    total_generated: int
    generation_timestamp: str
    is_demo: bool = False

class MarketingAgent:
    def __init__(self):
        self.agent_name = "Marketing Agent"
    
    def _create_demo_draft(self, prospect: ProspectResearch, score: LeadScore, business_profile: dict) -> EmailDraft:
        biz_name = business_profile.get("business_name", "Our Company")
        biz_services = business_profile.get("services", "AI automation services")
        
        return EmailDraft(
            company_name=prospect.company_name,
            subject=f"[DEMO DRAFT] Exploring AI Automation Partnership with {prospect.company_name}",
            body=f"""[DEMO EMAIL DRAFT - NOT FOR SENDING]

Dear {prospect.company_name} Team,

I hope this message finds you well. My name is [Your Name] from {biz_name}.

I've been researching innovative {prospect.industry} companies in {prospect.location}, and {prospect.company_name} caught my attention.

Based on our research, companies in your space often face challenges with:
- {score.potential_needs[0] if score.potential_needs else 'Process automation'}
- {score.potential_needs[1] if len(score.potential_needs) > 1 else 'Data management'}
- {score.potential_needs[2] if len(score.potential_needs) > 2 else 'Workflow optimization'}

At {biz_name}, we specialize in {biz_services}. We've helped similar companies reduce operational overhead by automating repetitive tasks.

I would love to schedule a brief 20-minute call to explore whether our solutions could benefit your team.

Would you be available for a quick conversation this week?

Best regards,
[Your Name]
{biz_name}
[Your Phone]
[Your Email]

---
Note: This is a personalized draft generated by BizPilot AI. Review and edit before sending.
Lead Score: {score.lead_score}/100 | Priority: {score.priority}""",
            marketing_angle=f"[DEMO] Focus on {prospect.industry} efficiency and AI automation ROI",
            personalization_notes=f"[DEMO] Personalized based on: Industry={prospect.industry}, Location={prospect.location}, Priority={score.priority}",
            recipient_email=prospect.contact_email if prospect.contact_email != "unknown" else "unknown",
            is_demo=True
        )
    
    async def generate_drafts(self, prospects: List[ProspectResearch], scores: List[LeadScore], business_profile: dict, min_score: int = 40) -> MarketingResult:
        """Generate email drafts for qualified prospects."""
        logger.info(f"Marketing Agent: Generating drafts for {len(prospects)} prospects")
        
        # Filter to qualified prospects only
        score_map = {s.company_name: s for s in scores}
        qualified = [(p, score_map[p.company_name]) for p in prospects if p.company_name in score_map and score_map[p.company_name].lead_score >= min_score]
        
        logger.info(f"Marketing Agent: {len(qualified)} prospects qualify (score >= {min_score})")
        
        drafts = []
        for prospect, score in qualified:
            if llm_service.is_demo_mode:
                draft = self._create_demo_draft(prospect, score, business_profile)
            else:
                draft = await self._llm_draft(prospect, score, business_profile)
            drafts.append(draft)
            await asyncio.sleep(0.1)
        
        return MarketingResult(
            drafts=drafts,
            total_generated=len(drafts),
            generation_timestamp=datetime.now(timezone.utc).isoformat(),
            is_demo=llm_service.is_demo_mode
        )
    
    async def _llm_draft(self, prospect: ProspectResearch, score: LeadScore, business_profile: dict) -> EmailDraft:
        """Use LLM to generate personalized email."""
        system_prompt = f"""You are an expert B2B copywriter. Write personalized, professional cold outreach emails.

Business offering these services: {business_profile}

RULES:
- Be professional and specific to the prospect
- Do NOT make false claims or fake familiarity  
- Do NOT promise specific ROI numbers you can't verify
- DO personalize based on their industry and known info
- Keep it concise (under 200 words body)
- Clear call to action"""

        user_prompt = f"""Write a cold email for:
Company: {prospect.company_name}
Industry: {prospect.industry}
Description: {prospect.description}
Location: {prospect.location}
Lead Score: {score.lead_score}/100
Potential Needs: {score.potential_needs}
Recommended Approach: {score.recommended_approach}

Return JSON with: subject, body, marketing_angle, personalization_notes"""

        try:
            response = await llm_service.generate(system_prompt, user_prompt)
            if isinstance(response, str):
                import re
                json_match = re.search(r'\{.*\}', response, re.DOTALL)
                data = json.loads(json_match.group() if json_match else response)
            else:
                data = response
            return EmailDraft(
                company_name=prospect.company_name,
                recipient_email=prospect.contact_email if prospect.contact_email != "unknown" else "unknown",
                **data
            )
        except Exception as e:
            logger.error(f"LLM draft failed for {prospect.company_name}: {e}")
            return self._create_demo_draft(prospect, score, business_profile)

marketing_agent = MarketingAgent()
